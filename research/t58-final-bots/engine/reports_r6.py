"""Round 6 report tables -> final/T58_FINAL_BOTS_ROUND6_2026-11-25_tables.md (narrative: final/T58_FINAL_BOTS_ROUND6_2026-11-25.md)."""
import pandas as pd
R = "research/t58_final_bots/research"; F = "research/t58_final_bots/final"
dev = pd.read_csv(f"{R}/final_dev_r6.csv"); h6 = pd.read_csv(f"{R}/final_h6_r6.csv"); mc = pd.read_csv(f"{R}/mc_r6.csv")
sf = pd.concat([pd.read_csv(f"{R}/shortfalls_final_dev_r6.csv"), pd.read_csv(f"{R}/shortfalls_final_h6_r6.csv")])
MA = ["p_pass", "med_days_pass", "bust", "ev", "pf", "sharpe", "max_dd", "worst_day", "f90_paid", "p_payout"]
MB = ["f90_paid", "p_payout", "ev", "pf", "worst_day", "max_dd", "cons_blocks_per30", "f90_bust"]
def fmt(v, m):
    if pd.isna(v): return "-"
    if m in ("p_pass", "bust", "p_payout", "f90_bust"): return f"{100 * v:.1f}%"
    if m in ("ev", "max_dd", "worst_day", "f90_paid"): return f"${v:,.0f}"
    return f"{v:.2f}"
def table(d, bots, plans, splits, ms, cost="stress"):
    out = ["| bot | plan | window | " + " | ".join(ms) + " | shortfalls vs baseline |", "|" + "---|" * (len(ms) + 4)]
    for pl in plans:
        for sp in splits:
            for b in bots:
                r = d[(d.bot == b) & (d.plan == pl) & (d.split == sp) & (d.cost == cost)]
                if r.empty: continue
                r = r.iloc[0]; s = sf[(sf.bot == b) & (sf.plan == pl) & (sf.split == sp) & (sf.cost == cost)]
                fl = "-" if b.startswith("baseline") or s.empty else (s.iloc[0]["fails"] if isinstance(s.iloc[0]["fails"], str) else "none")
                out.append(f"| {b} | {pl} | {sp} | " + " | ".join(fmt(r[m], m) for m in ms) + f" | {fl} |")
    return "\n".join(out)
L = ["# Round 6 tables (stress cost unless noted; generated by code/reports_r6.py)", "",
     "Windows: W1 2021-01-04 .. 2024-07-16, W2 2024-07-16 .. 2026-01-05, H6 2026-01-05 .. 2026-11-21; h3 2016-11-24 .. 2020-01-01,",
     "research 2020-2023, validation 2024-01 .. 2026-11-20. Every ES/NQ/GC day was already read in rounds 1-5: all of it is in-sample.", "",
     "## BOT-A (decision cells)", table(dev, ["baseline_A", "BOT-A-R4", "BOT-A-R6"], ["pro50", "pro100"], ["W1", "W2"], MA), "",
     "## BOT-A at base cost", table(dev, ["baseline_A", "BOT-A-R4", "BOT-A-R6"], ["pro50", "pro100"], ["W1", "W2"], MA, "base"), "",
     "## BOT-A continuity windows", table(dev, ["baseline_A", "BOT-A-R4", "BOT-A-R6"], ["pro50"], ["h3", "research", "validation"], MA), "",
     "## BOT-B", table(dev, ["baseline_B", "BOT-B-R4", "BOT-B-R6alt"], ["pro50", "pro100", "flex50"], ["W1", "W2"], MB), "",
     "## 2026 (H6, read once after FROZEN_PICKS_R6; in-sample for ES/NQ/GC)",
     table(h6, ["baseline_A", "BOT-A-R4", "BOT-A-R6", "baseline_B", "BOT-B-R4", "BOT-B-R6alt"], ["pro50", "pro100", "flex50"], ["H6"], MA), "",
     "## Monte Carlo (4,000 paths of 70 sessions each, stress; FULL 2016-11 .. 2026-11, OOS 2024-01 .. 2026-11)",
     "| bot | plan | pool | method | P(pass) | bust | P(payout) | 90-day EV | EV p5 | EV p95 |", "|---|---|---|---|---|---|---|---|---|---|"]
for _, r in mc.iterrows():
    L.append(f"| {r.bot} | {r.plan} | {r['pool']} | {r.method} | {100*r.p_pass:.1f}% | {100*r.bust:.1f}% | {100*r.p_payout:.1f}% | ${r.ev90:,.0f} | ${r.ev90_p5:,.0f} | ${r.ev90_p95:,.0f} |")
open(f"{F}/T58_FINAL_BOTS_ROUND6_2026-11-25_tables.md", "w").write("\n".join(L) + "\n"); print("ok")
