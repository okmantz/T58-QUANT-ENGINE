#!/usr/bin/env python
"""Turn reports/t58_hypotheses/results.json (+ bot_replays.json) into docs/T58_HYPOTHESIS_REPORT.md.

    python scripts/make_t58_report.py --results reports/t58_hypotheses --out docs/T58_HYPOTHESIS_REPORT.md
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def f(x, nd=1, pre="", suf=""):
    if x is None:
        return "-"
    try:
        return f"{pre}{float(x):,.{nd}f}{suf}"
    except (TypeError, ValueError):
        return str(x)


def table(head: list, rows: list) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def sc(d: dict, a: str) -> str:
    return f"{f(d.get(a))}%"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="reports/t58_hypotheses")
    ap.add_argument("--out", default="docs/T58_HYPOTHESIS_REPORT.md")
    a = ap.parse_args()
    R = json.loads((Path(a.results) / "results.json").read_text())
    bp = Path(a.results) / "bot_replays.json"
